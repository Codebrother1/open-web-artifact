test('fixture runner rejects wrong categories and unexpected success', async () => {
  // Guard the harness itself: negative fixtures may not pass just because any
  // exception happened (e.g. assertion errors or filesystem setup failures).
  assert.equal(errorCategory(new SyntaxError('host parser')), 'OWA_INVALID_JSON');
  assert.equal(errorCategory(Object.assign(new Error('irrelevant text'), { code: 'OWA_INVALID_PATH' })), 'OWA_INVALID_PATH');
  assert.equal(errorCategory(new Error('OWA_INVALID_PATH')), undefined);
  assert.equal(errorCategory(Object.assign(new Error(), { code: 'OTHER' })), 'OTHER');
  await assertFailure(async () => { throw new SyntaxError('host parser'); }, 'OWA_INVALID_JSON', 'parser mapping');
  await assertFailure(async () => { throw Object.assign(new Error('arbitrary wording'), { code: 'OWA_INVALID_PATH' }); }, 'OWA_INVALID_PATH', 'correct category');
  for (const wrongError of [new Error('OWA_INVALID_PATH'), Object.assign(new Error(), { code: 'OTHER' }), new SyntaxError('wrong operation')]) {
    await assert.rejects(() => assertFailure(async () => { throw wrongError; }, 'OWA_INVALID_PATH', 'wrong category'), { code: 'ERR_ASSERTION' });
  }
  await assert.rejects(() => assertFailure(async () => {}, 'OWA_INVALID_PATH', 'unexpected success'), { code: 'ERR_ASSERTION' });
});
